"""Is a photo AI-generated? Three checks, from strongest to weakest evidence.

1. Content Credentials (C2PA): a signed record that tools such as ChatGPT and Adobe Firefly attach to the
   images they make. We read it with the official c2pa library. A photo that declares itself AI-generated
   needs no trusted signature to count against it.
2. IPTC "digital source type" in the photo's XMP metadata, which Google and others write into generated images.
3. An AI-image detector (Sightengine, free tier): a model that judges the pixels. Optional, only runs when
   SIGHTENGINE_API_USER and SIGHTENGINE_API_SECRET are set.

1 and 2 run on the original file, before we strip its metadata. They catch AI images that were downloaded
as they are, but not screenshots or re-saved copies, so 3 is the backstop. None of them can prove a photo is
real. Google's SynthID watermark has no public API yet; the adjuster file says how to check it by hand.
"""
import io
import json

import requests

from core import config

AI_SOURCE_TYPES = {
    "trainedAlgorithmicMedia": "generated by AI",
    "compositeWithTrainedAlgorithmicMedia": "edited with AI",
}
SIGHTENGINE_URL = "https://api.sightengine.com/1.0/check.json"


def content_credentials(data):
    """{'ai_declared': bool, 'detail': str, 'has_credentials': bool} for the original file bytes."""
    result = {"ai_declared": False, "detail": "", "has_credentials": False}
    found = _from_c2pa(data, result) or _from_xmp(data)
    if found:
        result.update(ai_declared=True, detail=found)
    return result


def _from_c2pa(data, result):
    try:
        import c2pa
        reader = c2pa.Reader.try_create(io.BytesIO(data))
        if reader is None:
            return ""
        with reader:
            store = json.loads(reader.json())
    except Exception:            # unreadable or damaged credentials: treat as none
        return ""
    result["has_credentials"] = True
    manifest = store.get("manifests", {}).get(store.get("active_manifest"), {})
    tool = manifest.get("claim_generator") or ", ".join(
        g.get("name", "") for g in manifest.get("claim_generator_info", []) if isinstance(g, dict))
    for assertion in manifest.get("assertions", []):
        if not str(assertion.get("label", "")).startswith("c2pa.actions"):
            continue
        for action in assertion.get("data", {}).get("actions", []):
            source_type = str(action.get("digitalSourceType", "")).rsplit("/", 1)[-1]
            if source_type in AI_SOURCE_TYPES:
                agent = action.get("softwareAgent")
                agent = agent.get("name", "") if isinstance(agent, dict) else agent
                return f"Content Credentials say {AI_SOURCE_TYPES[source_type]} ({agent or tool or 'tool not named'})"
    return ""


def _from_xmp(data):
    for source_type, meaning in AI_SOURCE_TYPES.items():
        if f"digitalsourcetype/{source_type}".encode() in data:
            return f"Photo metadata says {meaning} (IPTC digital source type)"
    return ""


def detector_configured():
    return bool(config.SIGHTENGINE_API_USER and config.SIGHTENGINE_API_SECRET)


def detector_score(path):
    """Sightengine's AI-generated score (0 to 1) for one photo. {'score': float | None, 'error': str}."""
    if not detector_configured():
        return {"score": None, "error": "not configured"}
    try:
        with open(path, "rb") as photo:
            response = requests.post(SIGHTENGINE_URL, timeout=30, files={"media": photo}, data={
                "models": "genai", "api_user": config.SIGHTENGINE_API_USER,
                "api_secret": config.SIGHTENGINE_API_SECRET})
        body = response.json()
        if body.get("status") != "success":
            return {"score": None, "error": body.get("error", {}).get("message", "request failed")}
        return {"score": float(body["type"]["ai_generated"]), "error": ""}
    except Exception as exc:     # the detector is a backstop: never block a claim on it
        return {"score": None, "error": str(exc)}
